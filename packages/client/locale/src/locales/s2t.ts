/**
 * Convert a Simplified Chinese string into Traditional Chinese.
 * Handles software/UI terminology phrases first, then character-by-character conversion.
 */
export function toTraditionalChinese(input: string): string {
  if (!input) return input

  let result = input
  for (const [s, t] of PHRASES) {
    if (result.includes(s)) {
      result = result.replaceAll(s, t)
    }
  }

  let out = ''
  for (const char of result) {
    out += CHAR_MAP[char] ?? char
  }
  return out
}
